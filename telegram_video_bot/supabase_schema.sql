create table if not exists public.profiles (
    id bigint generated by default as identity primary key,
    platform text not null default 'tiktok',
    url text not null unique,
    display_name text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.videos (
    profile_id bigint not null references public.profiles(id) on delete cascade,
    video_id text not null,
    url text not null,
    title text not null,
    state text not null check (state in ('baseline', 'notified')),
    created_at timestamptz not null default now(),
    notified_at timestamptz,
    primary key (profile_id, video_id)
);

alter table public.profiles enable row level security;
alter table public.videos enable row level security;

grant usage on schema public to service_role;
grant all on public.profiles, public.videos to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.add_tiktok_profile(
    p_url text,
    p_display_name text,
    p_baseline_videos jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
    new_profile_id bigint;
begin
    insert into public.profiles (platform, url, display_name)
    values ('tiktok', p_url, p_display_name)
    on conflict (url) do nothing
    returning id into new_profile_id;

    if new_profile_id is null then
        return null;
    end if;

    insert into public.videos (profile_id, video_id, url, title, state)
    select new_profile_id, baseline.video_id, baseline.url, baseline.title, 'baseline'
    from jsonb_to_recordset(coalesce(p_baseline_videos, '[]'::jsonb))
        as baseline(video_id text, url text, title text)
    on conflict (profile_id, video_id) do nothing;

    return new_profile_id;
end;
$$;

revoke all on function public.add_tiktok_profile(text, text, jsonb)
    from public, anon, authenticated;
grant execute on function public.add_tiktok_profile(text, text, jsonb) to service_role;

notify pgrst, 'reload schema';
